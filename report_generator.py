def generate_csv_bytes(df, filename_hint='export') -> bytes:
    """
    Export DataFrame to UTF-8 encoded CSV bytes.

    Args:
        df: pandas DataFrame to export.
        filename_hint: Optional hint for filename (unused in byte generator).

    Returns:
        bytes: CSV encoded in UTF-8.
    """
    if df is None:
        return b""
    return df.to_csv(index=False).encode('utf-8')
